import assert from 'node:assert/strict'
import { createHash } from 'node:crypto'
import { readFile, writeFile } from 'node:fs/promises'
import { createRequire } from 'node:module'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import vm from 'node:vm'
import esbuild from '../../web/node_modules/esbuild/lib/main.js'

const here = path.dirname(fileURLToPath(import.meta.url)),
  root = path.resolve(here, '../../..'),
  require = createRequire(import.meta.url)
const engine = path.join(
    path.dirname(require.resolve('re2js')),
    'index.esm.js'
  ),
  enginePackage = JSON.parse(
    await readFile(path.join(path.dirname(engine), '../package.json'), 'utf8')
  )
assert.equal(enginePackage.version, '2.0.1')
const license = await readFile(
  path.join(path.dirname(engine), '../LICENSE'),
  'utf8'
)
const generated = await esbuild.build({
  absWorkingDir: root,
  stdin: {
    contents: `import {toMatcher} from './rust/web/src/upstream/repo-rules-matcher';
globalThis.__desktopMatchRules = function(patternsJSON,branch) {
  if (typeof patternsJSON !== 'string' || typeof branch !== 'string') throw new TypeError('Matcher requires JSON parameters and branch text');
  const parameters = JSON.parse(patternsJSON);
  if (!Array.isArray(parameters)) throw new TypeError('Matcher parameters must be an array');
  return JSON.stringify(parameters.map(rule => {
    if (rule === null || typeof rule !== 'object' || Array.isArray(rule) || typeof rule.operator !== 'string' || typeof rule.pattern !== 'string' || typeof rule.negate !== 'boolean') throw new TypeError('Invalid metadata matcher parameters');
    return toMatcher(rule)(branch);
  }));
};`,
    resolveDir: root,
    loader: 'ts',
  },
  bundle: true,
  write: false,
  platform: 'browser',
  format: 'iife',
  target: 'es2020',
  minify: true,
  legalComments: 'eof',
  banner: {
    js: `/*! Trusted static RE2JS 2.0.1 matcher. Generated by rust/tests/branch-rules-oracle/build-engine.mjs.\nGitHub Desktop shared matcher: Copyright (c) GitHub, Inc., MIT (repository LICENSE).\n${license.replaceAll(
      '*/',
      '* /'
    )}*/`,
  },
  plugins: [
    {
      name: 'pinned-re2js-esm',
      setup(build) {
        build.onResolve({ filter: /^re2js$/ }, () => ({ path: engine }))
      },
    },
  ],
})
assert.equal(generated.outputFiles.length, 1)
const artifact = generated.outputFiles[0].text
assert(
  !/\brequire\s*\(|\bmodule\.exports\b/.test(artifact),
  'Embedded matcher must not require CommonJS'
)
const sandbox = vm.createContext({})
vm.runInContext(artifact, sandbox, { timeout: 3000 })
assert.equal(typeof sandbox.__desktopMatchRules, 'function')
assert.deepEqual(
  JSON.parse(
    sandbox.__desktopMatchRules(
      JSON.stringify([{ operator: 'regex', pattern: '^.$', negate: false }]),
      '😀'
    )
  ),
  [true]
)
assert.equal(typeof sandbox.TextEncoder, 'undefined')
assert.equal(typeof sandbox.TextDecoder, 'undefined')
const destination = path.join(root, 'rust/crates/core/src/repo_rules/re2js.js'),
  licenseDestination = path.join(
    root,
    'rust/crates/core/src/repo_rules/RE2JS-LICENSE.txt'
  )
if (process.argv.includes('--check')) {
  assert.equal(
    await readFile(destination, 'utf8'),
    artifact,
    'Regenerate the trusted matcher bundle'
  )
  assert.equal(await readFile(licenseDestination, 'utf8'), license)
  process.stdout.write(
    'PASS: deterministic static RE2JS bundle and license match.\n'
  )
} else {
  await writeFile(destination, artifact)
  await writeFile(licenseDestination, license)
  process.stdout.write(
    `Generated trusted RE2JS matcher: ${Buffer.byteLength(
      artifact
    )} bytes, SHA256 ${createHash('sha256').update(artifact).digest('hex')}.\n`
  )
}
